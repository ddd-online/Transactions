/**
 * 取整口径：四舍五入、**远离零**（`f64::round`）。
 *
 * JS 的 `Math.round` 在半值上朝 `+∞`（`Math.round(-0.5) === -0`、`Math.round(-1.5) === -1`），
 * 与 `f64::round`（`-0.5 → -1`、`-1.5 → -2`）相反。负半值出现在浮亏率、涨跌幅、差额与均价
 * 这些地方，差一位就是界面上差 0.01。
 *
 * 从前这一行被抄在十一处（费用、金额、格式化、股票换算、成交流水行、更新速度、交易历史、
 * 持仓、统计，以及下单写入与编辑回放各一份），每一份字面相同 —— 每多一份，"改一次要全文件找"
 * 就多一分。需要「四舍五入、远离零」的地方都从这里 import，不要再抄一份。
 *
 * 只对**恒为非负**的数做四舍五入时 `Math.round` 与它等价（台账的均价、涨跌幅的两位小数就是
 * 这样），那几处不必改动；但别在可能为负的值上直接写 `Math.round` —— 那正是两者分道的地方。
 */
export function roundHalfAwayFromZero(value: number): number {
  return value < 0 ? -Math.round(-value) : Math.round(value)
}
